#!/usr/bin/env python3
# ============================================================
#  ooooc_reg.py —— O语言符号长度注册表生成器
#
#  超智慧编程，真实不虚：名字的长度不该由人类来数。
#
#  用法：
#      python ooooc_reg.py 名字1 名字2 ...          # v3 兼容模式
#      python ooooc_reg.py --scan a.c b.h > reg.h  # 扫描源码
#
#  生成内容：
#      #define OOOOC_LENOF_Animal 6
#      ...
#
#  为什么需要它：N_MED_AUTO 要在预处理阶段把名字长度拼进符号，
#  而 C 预处理器不会数数。于是我们用 Python 数。
# ============================================================
import re
import sys
from pathlib import Path

IDENT_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")

HEADER_BEGIN = """// generated by {origin} -- do not edit
// O language symbol-length registry.
#ifndef OOOOC_REGISTRY_H
#define OOOOC_REGISTRY_H
"""

HEADER_END = """#endif // OOOOC_REGISTRY_H
"""


def read_text(path):
    """按 UTF-8 读取；坏字节替换掉，不让一个文件毁掉整个注册表。"""
    return Path(path).read_text(encoding="utf-8", errors="replace")


def collect_identifiers(paths):
    """收集所有文件里出现过的标识符，返回排序后的集合。"""
    names = set()
    for p in paths:
        names.update(IDENT_RE.findall(read_text(p)))
    return names


def render_registry(names, origin="ooooc_reg.py"):
    """把名字集合渲染成 C 头文件文本。"""
    lines = [HEADER_BEGIN.format(origin=origin)]
    for name in sorted(names):
        lines.append("#define OOOOC_LENOF_{0} {1}\n".format(name, len(name)))
    lines.append(HEADER_END)
    return "".join(lines)


def _usage():
    return (
        "用法:\n"
        "  python ooooc_reg.py 名字1 名字2 ...\n"
        "  python ooooc_reg.py --scan 源文件... \n"
    )


def main(argv):
    args = argv[1:]
    scan = False

    if args and args[0] in ("-h", "--help"):
        sys.stdout.write(_usage())
        return 0
    if args and args[0] == "--scan":
        scan = True
        args = args[1:]

    if not args:
        sys.stderr.write(_usage())
        return 2

    if scan:
        names = collect_identifiers(args)
    else:
        names = []
        for name in args:
            if not name.isidentifier():
                sys.stderr.write("错误: '{0}' 不是合法标识符，O语言拒绝\n".format(name))
                return 2
            names.append(name)

    sys.stdout.write(render_registry(names))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
